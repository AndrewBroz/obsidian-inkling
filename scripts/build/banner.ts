import * as Bun from "bun";

export async function banner(buildType: string) {
	const manifest = await Bun.file("manifest.json").json();

	// EXPL: No build time or other machine-dependent text: rebuilding a release tag must give a byte-identical main.js.
	return `/*
=======================================================
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin at https://github.com/AndrewBroz/obsidian-inkling
	
  ${manifest.name} — ${manifest.version} [${buildType.toUpperCase()} BUILD]
	Author: ${manifest.author}
	Version: ${manifest.version}
	
=======================================================
*/
`;
}
